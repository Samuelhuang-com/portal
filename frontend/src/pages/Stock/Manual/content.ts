// ── 區塊型別 ─────────────────────────────────────────────────────────────────

/** 流程圖的一個步驟 */
export interface FlowStep {
  /** 步驟名稱（框內粗體） */
  label: string
  /** 補充一行（框內小字） */
  sub?: string
  /** 誰做（框上方的角色標籤） */
  who?: string
  /** 顏色語意：一般／完成（綠）／要注意（黃）／終止或不入帳（灰） */
  tone?: 'normal' | 'ok' | 'warn' | 'stop'
  /** 分支：畫在框下方的紅色虛線說明，例如「退回 → 回到草稿」 */
  alt?: string
}

/** 流程圖的一列（多列＝多個階段，由上往下讀） */
export interface FlowRow {
  name?: string
  steps: FlowStep[]
}

export type Block =
  | { t: 'p'; text: string }
  | { t: 'ul'; items: string[] }
  | { t: 'ol'; items: string[] }
  | { t: 'note'; text: string }        // 藍底：補充說明
  | { t: 'caution'; text: string }     // 黃底：要注意的事
  | { t: 'wrong'; text: string }       // 紅底：常見誤解
  | { t: 'table'; head: string[]; rows: string[][]; caption?: string }
  | { t: 'flow'; title: string; rows: FlowRow[]; caption?: string }

export interface SubSection {
  id: string
  title: string
  /** 對應的 Portal 頁面（顯示「前往此功能」按鈕） */
  route?: string
  blocks: Block[]
}

export interface Section {
  id: string
  title: string
  intro?: string
  subs: SubSection[]
}

