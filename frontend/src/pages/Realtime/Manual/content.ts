/** 供全文搜尋用：把一個小節的所有文字攤平 */
export function subSectionText(sub: SubSection): string {
  const parts: string[] = [sub.title]
  for (const b of sub.blocks) {
    if (b.t === 'p' || b.t === 'note' || b.t === 'caution' || b.t === 'wrong') parts.push(b.text)
    else if (b.t === 'ul' || b.t === 'ol') parts.push(...b.items)
    else if (b.t === 'table') {
      parts.push(...b.head)
      for (const r of b.rows) parts.push(...r)
      if (b.caption) parts.push(b.caption)
    }
  }
  return parts.join(' ')
}

