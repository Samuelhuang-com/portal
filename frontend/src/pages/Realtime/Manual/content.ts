// ── 區塊型別 ─────────────────────────────────────────────────────────────────

export type Block =
  | { t: 'p'; text: string }
  | { t: 'ul'; items: string[] }
  | { t: 'ol'; items: string[] }
  | { t: 'note'; text: string }        // 藍底：補充說明
  | { t: 'caution'; text: string }     // 黃底：要注意的事
  | { t: 'wrong'; text: string }       // 紅底：常見誤解
  | { t: 'table'; head: string[]; rows: string[][]; caption?: string }

export interface SubSection {
  id: string
  title: string
  /** 對應的 Portal 頁面（顯示「前往此功能」按鈕） */
  route?: string
  blocks: Block[]
}

export interface Section {
  id: string
  title: string
  intro?: string
  subs: SubSection[]
}

