/** 供搜尋用：把一個章節的所有文字攤平 */
export function subSectionText(sub: SubSection): string {
  const parts: string[] = [sub.title, sub.gap || '']
  for (const b of sub.blocks) {
    switch (b.t) {
      case 'p':
      case 'note':
      case 'caution':
      case 'sub':
        parts.push('text' in b ? b.text : b.title)
        break
      case 'ul':
      case 'ol':
      case 'formula':
        parts.push(b.items.join(' '))
        break
      case 'table':
        parts.push(b.head.join(' '), b.rows.map((r) => r.join(' ')).join(' '), b.caption || '')
        break
      case 'live':
        parts.push('目前基準 即時 資料涵蓋')
        break
    }
  }
  return parts.join(' ')
}
