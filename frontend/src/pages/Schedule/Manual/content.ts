/** 供搜尋用：把一個小節的所有文字攤平成一個字串 */
export function subSectionText(sub: SubSection): string {
  const parts: string[] = [sub.title]
  sub.blocks.forEach((b) => {
    switch (b.t) {
      case 'p': case 'note': case 'caution': case 'wrong':
        parts.push(b.text); break
      case 'ul': case 'ol':
        parts.push(...b.items); break
      case 'table':
        parts.push(...b.head, ...b.rows.flat(), b.caption ?? ''); break
    }
  })
  return parts.join(' ')
}

