export function subSectionText(sub: SubSection): string {
  const parts: string[] = [sub.title, sub.gap || '']
  for (const b of sub.blocks) {
    switch (b.t) {
      case 'p':
      case 'note':
      case 'caution':
        parts.push(b.text)
        break
      case 'sub':
        parts.push(b.title)
        break
      case 'ul':
      case 'ol':
      case 'formula':
        parts.push(b.items.join(' '))
        break
      case 'table':
        parts.push(b.head.join(' '), b.rows.map((r) => r.join(' ')).join(' '), b.caption || '')
        break
      default:
        break
    }
  }
  return parts.join(' ')
}
