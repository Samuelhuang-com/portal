UNCATEGORIZED = "未分類"
PENDING_NOTE = "待定位：請用「編輯點位」拖到正確位置（拖過即視為已校正）"


def normalize_name(name: str | None) -> str:
    """保養項目名稱正規化：去頭尾、連續空白合併成一個（Ragic 與畫面顯示的空白可能不同）"""
    return " ".join((name or "").split())


def static_groups(module: str) -> list[dict[str, Any]]:
    """點位清單裡的資料來源（GroupMeta）。多樓層者 shared_label＝「N 層共用一筆」。"""
    return [
        {
            "source_ref":   ref,
            "label":        ref,
            "system":       cat or UNCATEGORIZED,
            "shared_label": f"{len(floors)} 層共用一筆" if len(floors) > 1 else "",
        }
        for ref, cat, _txt, floors in PM_ITEMS.get(module, [])
    ]


def pending_xy(i: int) -> tuple[float, float]:
    """待定位排列：圖左上，每欄 13 點，超過往右另起一欄（座標維持 0～1）"""
    col, row = divmod(i, 13)
    return round(0.04 + 0.07 * col, 3), round(0.07 + 0.065 * row, 3)


_tbl = sa.table(
    TABLE,
    sa.column("attrs", sa.JSON(none_as_null=True)),
    *(sa.column(c) for c in (
        "module", "floor_key", "x", "y", "label", "equipment_code", "source_ref", "placement", "note",
        "sort_order", "is_active", "created_by", "updated_by", "created_at", "updated_at",
    )),
)


def seed_pm_points(conn, module: str, tag: str) -> int:
    """模組一筆點位都沒有時寫入待定位點位；已有任何點位（含已停用）就不動。回傳寫入筆數。"""
    if module not in PM_ITEMS:
        return 0
    n = conn.execute(sa.text(f"SELECT COUNT(*) FROM {TABLE} WHERE module = :m"), {"m": module}).scalar() or 0
    if n:
        return 0
    now, rows = twnow(), []
    per_floor: dict[str, int] = {}
    order = 0
    for ref, _cat, txt, floors in PM_ITEMS[module]:
        for fk in floors:
            i = per_floor.get(fk, 0)
            per_floor[fk] = i + 1
            x, y = pending_xy(i)
            rows.append({
                "module": module, "floor_key": fk, "x": x, "y": y, "label": ref[:100],
                "equipment_code": None, "source_ref": ref, "placement": "pending",
                "attrs": {"位置說明": txt} if txt else None, "note": PENDING_NOTE,
                "sort_order": order, "is_active": True, "created_by": tag, "updated_by": tag,
                "created_at": now, "updated_at": now,
            })
            order += 1
    if rows:
        conn.execute(_tbl.insert(), rows)
    return len(rows)
